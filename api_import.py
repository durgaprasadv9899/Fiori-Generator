"""
api_import.py — bring existing applications into the studio workspace: a project ZIP (any UI5 /
Fiori project folder) or an app deployed on Cloud Foundry (its source package). Apps generated by
the studio carry their design (evoke-app.json) and are restored fully — reopen, change, regenerate,
deploy; client Fiori apps are imported as files with their service metadata.
"""

from __future__ import annotations

from typing import Callable, Dict, Optional

import app_import


def _flat(text: Dict[str, str], wp: str) -> Dict[str, str]:
    """Project layout (webapp/…) → the studio's version layout (webapp files at the top)."""
    out = {}
    for p, c in text.items():
        if p.startswith(".git/") or "/node_modules/" in "/" + p or p.startswith("mta_archives/"):
            continue
        out[p[len(wp):] if wp and p.startswith(wp) else p] = c
    return out


def _deploy_meta_generated(d: Dict, info: Dict) -> Dict:
    """Deployment settings of a studio-generated app (as the studio computes them when generating)."""
    app_id = d.get("app_id") or info.get("app_id") or ""
    if d.get("standalone"):
        return {"app_id": app_id, "services": [], "standalone": True, "db": (d["standalone"] or {}).get("db", "sqlite")}
    import multi_service as ms
    from odata_config import ODataService, AUTH_NONE
    use_existing = bool(d.get("use_existing_destination"))
    common = dict(auth_type=AUTH_NONE if use_existing else (d.get("auth_type") or AUTH_NONE),
                  use_existing_destination=use_existing, destination=(d.get("destination") or "").strip(),
                  on_premise=bool(d.get("on_premise")))
    svcs = [ODataService(id="mainService", url=d.get("service_url") or info.get("service_path") or "",
                         odata_version=info.get("odata_version", "2.0"), is_primary=True, **common)]
    used = {"mainService"}
    for s in d.get("services") or []:
        svcs.append(ODataService(id=ms.alias_for(s.get("service_url", ""), used), url=s.get("service_url", ""),
                                 odata_version=info.get("odata_version", "2.0"), **common))
    return {"app_id": app_id, "services": [{"id": s.id, "url": s.url, "auth_type": s.auth_type, "dest_name": s.dest_name(),
                                            "needs_auth": s.needs_auth(), "is_real": s.is_real(),
                                            "use_existing_destination": s.use_existing_destination,
                                            "on_premise": s.on_premise} for s in svcs]}


def import_files(store, user, text: Dict[str, str], origin: str, say: Callable[[str], None] = lambda m: None,
                 name: Optional[str] = None) -> Dict:
    """Analyse an app's files and save it as a new project with one version."""
    say("Analysing the project…")
    info = app_import.analyze(text)
    files = _flat(text, info.get("webapp") or "")
    kind = info["kind"]
    if kind == "generated":
        d = info["design"] or {}
        sa_state = d.get("standalone")
        snapshot = {
            "app_mode": "standalone" if sa_state else "sap",
            "user_prompt": d.get("requirement", ""), "app_id_v": d.get("app_id") or info["app_id"],
            "md_edmx": info.get("metadata", ""), "md_service_url_val": d.get("service_url") or info.get("service_path", ""),
            "md_extra": info.get("extra_services") or [],
            "md_use_existing_dest": bool(d.get("use_existing_destination")), "md_dest_name_val": d.get("destination", ""),
            "md_on_premise": bool(d.get("on_premise")), "md_auth": d.get("auth_type") or "NoAuthentication",
            "theme_v": d.get("theme") or "sap_horizon",
            "bp_design": {"blueprint": d.get("blueprint"), "notes": [], "source": "imported", "spec": d.get("spec"),
                          "coverage": d.get("coverage") or [], "steps": []},
            "deploy_meta": _deploy_meta_generated(d, info),
        }
        if sa_state:
            snapshot["standalone"] = sa_state
        mode = "standalone" if sa_state else "sap"
        title = ((d.get("blueprint") or {}).get("app") or {}).get("title") or info.get("title") or info["app_id"]
        say(f"Studio-generated app — design restored ({title}).")
    else:
        snapshot = {"app_mode": "sap", "import_kind": kind, "md_edmx": info.get("metadata", ""),
                    "md_service_url_val": info.get("service_path", ""), "app_id_v": info["app_id"],
                    "user_prompt": f"Existing {kind.upper()} app {info.get('title') or info['app_id']}"}
        mode = "import"
        title = info.get("title") or info["app_id"] or "Imported app"
        if title.startswith("{{"):
            title = info["app_id"] or "Imported app"
        say(f"Client Fiori app ({kind}) — imported with its files"
            + (" and service metadata." if info.get("metadata") else "; no local service metadata found."))
    proj = store.create_project(name or title, user, mode, app_id=info["app_id"] or snapshot.get("app_id_v", ""),
                                description=f"Imported from {origin}. " + (snapshot.get("user_prompt") or "")[:240])
    v = store.save_version(proj["id"], user, snapshot, files, label=f"Imported from {origin}")
    store.audit(user, proj["id"], "project.import", {"origin": origin, "kind": kind, "files": len(files)})
    say(f"Saved as project “{proj['name']}”, version {v['number']} ({len(files)} files).")
    return {"project_id": proj["id"], "version_id": v["id"], "kind": kind, "name": proj["name"],
            "notes": info.get("notes") or [], "files": len(files)}


def import_zip(store, user, data: bytes, filename: str = "project.zip") -> Dict:
    """A studio workspace export (project.json) or any project folder as ZIP."""
    import io
    import zipfile
    try:
        names = set(zipfile.ZipFile(io.BytesIO(data)).namelist())
    except zipfile.BadZipFile as e:
        raise ValueError(f"Not a ZIP file: {e}") from e
    if "project.json" in names:
        p = store.import_project(data, user)
        return {"project_id": p["id"], "name": p["name"], "kind": "workspace export"}
    text, _binary = app_import.read_zip(data)
    return import_files(store, user, text, filename)


def import_cf(store, user, app_name: str, cf_home: Optional[str], say: Callable[[str], None]) -> Dict:
    say(f"Downloading the source package of {app_name} from Cloud Foundry…")
    data = app_import.download_cf_app(app_name, cf_home=cf_home)
    say(f"Downloaded {len(data) // 1024} KB.")
    text, _binary = app_import.read_zip(data)
    return import_files(store, user, text, f"Cloud Foundry ({app_name})", say)
